export const normalizeText = (text) => {
  return (text || '')
    .toLowerCase()
    .replace(/sumatera/g, 'sumatra')
    .replace(/jogja/g, 'yogyakarta')
    .replace(/nusra/g, 'nusa tenggara')
    .replace(/kalbar|kaltim|kalteng|kalsel|kaltra/g, 'kalimantan')
    .replace(/sulut|sulteng|sulsel|sultra/g, 'sulawesi')
    .replace(/sumut|sumbar|sumsel/g, 'sumatra')
    .trim();
};

export const matchesSearch = (dest, query) => {
  if (!query || query.trim() === '') return true;
  const qNorm = normalizeText(query);
  
  const targetStrings = [
    dest.name,
    dest.regionId,
    dest.regionName,
    dest.province,
    dest.locationDesc,
    dest.strategicPotential,
    dest.geologicalContext,
    dest.type,
    dest.island || ''
  ].map(s => normalizeText(s));

  return targetStrings.some(str => str.includes(qNorm));
};

